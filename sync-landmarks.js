const fs = require('fs');
const path = require('path');

const landmarkDir = path.join(__dirname, 'resources', 'images', 'landmark');
const jsonPath = path.join(landmarkDir, 'landmarks.json');
const jsDataPath = path.join(landmarkDir, 'landmarks-data.js');

const IMAGE_EXTENSIONS = new Set(['.jpg', '.jpeg', '.png', '.webp', '.avif', '.gif']);

try {
    if (!fs.existsSync(landmarkDir)) {
        console.error('❌ 랜드마크 디렉토리를 찾을 수 없습니다:', landmarkDir);
        process.exit(1);
    }

    const files = fs.readdirSync(landmarkDir);
    const imageFiles = files.filter(file => {
        // 백업 임시 파일(예: mangrove~.png)이나 숨김 파일 제외
        if (file.endsWith('~') || file.includes('~') || file.startsWith('.')) return false;
        const ext = path.extname(file).toLowerCase();
        return IMAGE_EXTENSIONS.has(ext);
    });

    // 1. landmarks.json 갱신
    fs.writeFileSync(jsonPath, JSON.stringify(imageFiles, null, 2), 'utf-8');

    // 2. landmarks-data.js (file:/// 로컬 CORS 우회 및 즉각 로딩용) 갱신
    const jsContent = '/* Auto-generated by sync-landmarks.js - DO NOT EDIT MANUALLY */\n' +
                      'window.EZREMS_LANDMARK_IMAGES = ' + JSON.stringify(imageFiles, null, 2) + ';\n';
    fs.writeFileSync(jsDataPath, jsContent, 'utf-8');

    console.log('✅ [ezREMS] 랜드마크 이미지 목록이 성공적으로 동기화되었습니다!');
    console.log('📁 등록된 이미지 (' + imageFiles.length + '개):', imageFiles.join(', '));
    console.log('📄 landmarks.json 갱신 완료: ' + jsonPath);
    console.log('📄 landmarks-data.js 갱신 완료: ' + jsDataPath);
} catch (err) {
    console.error('❌ 동기화 중 오류 발생:', err.message);
    process.exit(1);
}
